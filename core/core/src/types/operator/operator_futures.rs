/// [`Operator`] produces this future.
///
/// The future consumes its inputs when it begins executing.
///
/// # NOTES
///
/// OpenDAL uses this type as an implementation detail. Users should not use it directly.
pub struct OperatorFuture<I, O, F: Future<Output = Result<O>>> {
    /// The composed context used to execute operations.
    ctx: OperationContext,
    /// The composed service to the underlying object storage.
    srv: Servicer,
    /// The path of string
    path: String,
    /// The input args
    args: I,
    /// The function which will move all the args and return a static future
    f: fn(OperationContext, Servicer, String, I) -> F,
}

impl<I, O, F: Future<Output = Result<O>>> OperatorFuture<I, O, F> {
    /// # NOTES
    ///
    /// OpenDAL uses this type as an implementation detail. Users should not use it directly.
    pub(crate) fn new(
        ctx: OperationContext,
        srv: Servicer,
        path: String,
        args: I,
        f: fn(OperationContext, Servicer, String, I) -> F,
    ) -> Self {
        OperatorFuture {
            ctx,
            srv,
            path,
            args,
            f,
        }
    }
}

impl<I, O, F> IntoFuture for OperatorFuture<I, O, F>
where
    F: Future<Output = Result<O>>,
{
    type Output = Result<O>;
    type IntoFuture = F;

    fn into_future(self) -> Self::IntoFuture {
        (self.f)(self.ctx, self.srv, self.path, self.args)
    }
}

