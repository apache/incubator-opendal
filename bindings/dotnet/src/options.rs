/// valid for the duration of the call.
pub(crate) fn read_options<T: NativeOptions>(
    options: *const T,
) -> Result<T::Options, OpenDALError> {
    match unsafe { options.as_ref() } {
        Some(options) => options.to_options(),
        None => Ok(T::Options::default()),
    }
}

/// Build a byte range from `offset` and `length`, or from `suffix_length`
/// for a suffix range.
fn range(
    offset: u64,
    length: Option<u64>,
    suffix_length: Option<u64>,
) -> Result<BytesRange, OpenDALError> {
    if let Some(size) = suffix_length {
        if offset > 0 || length.is_some() {
            return Err(config_invalid_error(
                "suffix_length cannot be combined with offset or length",
            ));
        }
        return Ok(BytesRange::suffix(size));
    }

    Ok(match validate_read_range_end(offset, length)? {
        Some(end) => (offset..end).into(),
        None => (offset..).into(),
    })
}

