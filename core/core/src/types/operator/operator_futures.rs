    ///
    /// Refer to [`options::ReaderOptions::if_modified_since`] for the full contract.
    ///
    /// ```
    /// # use opendal_core::Result;
    /// use jiff::Timestamp;
    /// use opendal_core::Operator;
    /// # async fn test(op: Operator, time: Timestamp) -> Result<()> {
